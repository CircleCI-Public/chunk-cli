#!/usr/bin/env bash
# Bring README.md and docs/ back in line with the CLI, then open (or refresh)
# a pull request with the result. Never pushes to main.
#
# Needs: claude (Claude Code CLI), gh, go, plus ANTHROPIC_API_KEY and GITHUB_TOKEN.
set -euo pipefail

: "${ANTHROPIC_API_KEY:?ANTHROPIC_API_KEY is required}"
: "${GITHUB_TOKEN:?GITHUB_TOKEN is required}"

REPO="CircleCI-Public/chunk-cli"
BASE="main"
BRANCH="docs/readme-sync"

git config user.name "chunk-docs-sync"
git config user.email "noreply@circleci.com"
git remote set-url origin "https://x-access-token:${GITHUB_TOKEN}@github.com/${REPO}.git"
git fetch origin "$BASE"
git checkout -B "$BRANCH" "origin/${BASE}"

go build -o dist/chunk .
dist/chunk commands > /tmp/chunk-commands.txt

claude -p "$(cat <<'EOF'
README.md has drifted from what chunk can actually do. Bring it up to date.

Ground truth:
- /tmp/chunk-commands.txt is the full command tree from `chunk commands`.
- `dist/chunk <command> --help` shows flags and behavior for any command.
- docs/CLI.md, docs/GETTING_STARTED.md and AGENTS.md describe intent.

Do:
- Make the README Commands block match the command tree exactly: add missing
  commands, remove ones that no longer exist.
- Make sure every top-level capability (sidecars, validate, factory, watch,
  mutate, ...) is described, and the docs table lists every file in docs/.
- Check the environment variable table against `dist/chunk --help`.
- Verify any flag or example you keep or add against --help output.

Don't:
- Rewrite prose that is still correct, or change tone or structure needlessly.
- Touch anything outside README.md and docs/.
- Invent behavior. If you cannot verify something, leave it as it is.

If README.md and docs/ are already accurate, change nothing.
EOF
)" --allowedTools "Read" "Edit" "Bash(dist/chunk:*)" "Bash(cat:*)" "Bash(ls:*)" "Bash(git diff:*)"

if git diff --quiet -- README.md docs; then
  echo "README and docs are up to date; nothing to do."
  exit 0
fi

git add README.md docs
git commit -m "docs: sync README with the current CLI" -m "Generated by the scheduled docs-sync job. Review before merging."
git push --force-with-lease origin "$BRANCH"

if gh pr view "$BRANCH" --repo "$REPO" --json state --jq '.state' 2>/dev/null | grep -q OPEN; then
  echo "An open docs-sync PR already exists; branch updated."
  exit 0
fi

gh pr create --repo "$REPO" --base "$BASE" --head "$BRANCH" \
  --title "docs: sync README with the current CLI" \
  --body "Opened by the scheduled \`docs-sync\` job (.circleci/config.yml). It compares README.md and docs/ against \`chunk commands\` and \`--help\` output. Please review every change before merging."
