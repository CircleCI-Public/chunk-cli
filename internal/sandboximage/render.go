package sandboximage

import (
	"path"
	"strings"
)

// DefaultDockerfile is where chunk init writes the rendered Dockerfile,
// relative to the repo root.
const DefaultDockerfile = "Dockerfile.chunk"

// depsDir is the scratch directory the dependency layer warms the store in.
const depsDir = "/tmp/chunk-deps"

// agentKit is the same for every repo: the tools the factory's own scripts use
// and the Claude Code CLI. Package installs need root, so the user is switched
// around them; %s is the base image's user, and the lines are dropped for root.
const (
	kitPackages = `RUN apt-get update && apt-get install -y --no-install-recommends \
      git coreutils procps ca-certificates curl bash \
 && rm -rf /var/lib/apt/lists/* \
 && git config --system safe.directory '*'
`
	kitClaude = `RUN curl -fsSL https://claude.ai/install.sh | bash && test -x "$HOME/.local/bin/claude"
`
	kitCmd = "CMD [\"sleep\", \"infinity\"]\n"
)

// Render writes the Dockerfile for r. It is pure.
func Render(r Recipe) string {
	var b strings.Builder
	b.WriteString("# syntax=docker/dockerfile:1\n")
	b.WriteString("# Factory sandbox for `chunk factory build --backend docker`.\n")
	b.WriteString("# Generated by `chunk init`; edit freely, chunk will not overwrite it.\n")
	b.WriteString("# The repo is bind-mounted at run time, so this image holds tools, not source.\n")
	b.WriteString("FROM " + r.Base + "\n")
	if r.Deps != nil {
		for _, kv := range r.Deps.Env {
			b.WriteString("ENV " + kv[0] + "=" + strings.ReplaceAll(kv[1], "{home}", r.Home()) + "\n")
		}
	}
	b.WriteString("ENV PATH=" + r.Home() + "/.local/bin:$PATH\n")

	if r.Unknown() {
		b.WriteString("\n# --- toolchain -------------------------------------------------------------\n")
		b.WriteString("# chunk did not recognise this repo's stack. Add its toolchain here (compilers,\n")
		b.WriteString("# runtimes, system libraries) so the validation commands can run.\n")
	} else if sys := r.Env.SetupStep("system"); sys != "" && r.BaseFrom == BaseFromDetected {
		b.WriteString("\n# --- toolchain -------------------------------------------------------------\n")
		b.WriteString(asUser("root", r.User, "RUN "+sys+"\n"))
	}

	if r.Deps != nil && len(r.Manifests) > 0 {
		b.WriteString("\n# --- dependencies: rebuilt when these files change -------------------------\n")
		b.WriteString(r.depsLayer())
	}

	b.WriteString("\n# --- chunk agent kit -------------------------------------------------------\n")
	b.WriteString(asUser("root", r.User, kitPackages))
	b.WriteString(kitClaude)
	b.WriteString(kitCmd)
	return b.String()
}

// asUser runs block as user, then restores the base image's user. A root base
// image needs no switching.
func asUser(user, restore, block string) string {
	if restore == "" || restore == user {
		return block
	}
	return "USER " + user + "\n" + block + "USER " + restore + "\n"
}

// depsLayer COPYs the manifests, one directory at a time so their relative
// paths survive, and warms the store from them.
func (r Recipe) depsLayer() string {
	var b strings.Builder
	chown := ""
	if r.nonRoot() {
		chown = "--chown=" + r.User + " "
	}
	var dirs []string
	byDir := map[string][]string{}
	for _, m := range r.Manifests {
		dir := path.Dir(m)
		if _, ok := byDir[dir]; !ok {
			dirs = append(dirs, dir)
		}
		byDir[dir] = append(byDir[dir], m)
	}
	for _, dir := range dirs {
		dest := depsDir + "/"
		if dir != "." {
			dest += dir + "/"
		}
		b.WriteString("COPY " + chown + strings.Join(byDir[dir], " ") + " " + dest + "\n")
	}
	steps := []string{"cd " + depsDir}
	if r.Deps.Prepare != "" {
		steps = append(steps, r.Deps.Prepare)
	}
	steps = append(steps, r.Deps.Warm, "rm -rf "+depsDir)
	b.WriteString("RUN " + strings.Join(steps, " && ") + "\n")
	return b.String()
}
